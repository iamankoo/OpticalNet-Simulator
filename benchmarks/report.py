"""Builds benchmarks/RESULTS.md from raw benchmark JSON files (nothing is typed by hand).

    python benchmarks/report.py --dir build/benchout --out benchmarks/RESULTS.md [--env "text describing the machine"]

Input files: cpp_before_N.json, cpp_after_N.json (opticalnet_bench --json) and api_before_N.json, api_after_N.json
(bench_api.py --json). Runs are interleaved (before, after, before, after). For each benchmark the table shows the
mean of the per-run medians, and speedup = before / after computed from those means. The C++ checksum column
compares the fingerprint of the computed results (paths, metrics) between all before and after runs.
"""
import argparse
import glob
import json
import statistics
from pathlib import Path


def load(pattern):
    return [json.load(open(p, encoding="utf-8")) for p in sorted(glob.glob(pattern))]


def by_name(runs):
    table = {}
    for run in runs:
        for row in run["results"]:
            table.setdefault(row["name"], []).append(row)
    return table


def fmt_ms(ms):
    return f"{ms / 1000:.2f} s" if ms >= 10000 else f"{ms:.1f} ms" if ms >= 100 else f"{ms:.2f} ms"


def section(title, before, after, show_checksum):
    names = [n for n in before if n in after]
    lines = [f"### {title}", "", "| Benchmark | Workload | Before | After | Speedup |" + (" Results identical |" if show_checksum else ""),
             "|---|---|---:|---:|---:|" + ("---|" if show_checksum else "")]
    for name in names:
        b, a = before[name], after[name]
        bm = statistics.mean(r["median_ms"] for r in b)
        am = statistics.mean(r["median_ms"] for r in a)
        row = f"| `{name}` | {a[0]['workload']} | {fmt_ms(bm)} | {fmt_ms(am)} | {bm / am:.2f}x |"
        if show_checksum:
            sums = {r.get("checksum", "") for r in b + a}
            row += " n/a |" if sums == {"0"} else (" yes |" if len(sums) == 1 else " **NO** |")
        lines.append(row)
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dir", default="build/benchout")
    parser.add_argument("--out", default="benchmarks/RESULTS.md")
    parser.add_argument("--env", default="")
    args = parser.parse_args()
    d = args.dir
    cb, ca = load(f"{d}/cpp_before_*.json"), load(f"{d}/cpp_after_*.json")
    ab, aa = load(f"{d}/api_before_*.json"), load(f"{d}/api_after_*.json")
    out = ["# OpticalNet benchmark results", "",
           "Generated by `benchmarks/report.py` from raw JSON produced by `opticalnet_bench` and `bench_api.py`. "
           "Every number below was measured; nothing is estimated.", ""]
    if args.env:
        out += ["**Environment:** " + args.env, ""]
    out += [f"**Method:** each benchmark is run with {cb[0]['repeats']} repetitions per run and the median is taken; the "
            f"before/after binaries were run alternately ({len(cb)} runs each) on the same machine, and the table shows the "
            "mean of the per-run medians. \"Before\" is the code at commit `44755a7` (end of Phase 9); \"after\" is the "
            "Phase 10 code. Speedup = before / after. Fixed seeds and generated topologies make the workloads identical "
            "in both builds; the checksum column confirms the computed results are bit-identical.", ""]
    if cb and ca:
        out += section("C++ engine (Release build, -O3)", by_name(cb), by_name(ca), True) + [""]
    if ab and aa:
        out += section("Python binding and FastAPI (in-process TestClient, real compiled extension)", by_name(ab), by_name(aa), False) + [""]
    if cb and ca:
        table = by_name(ca)
        base = statistics.mean(r["median_ms"] for r in table["study.workers_1"])
        out += ["### Multithreaded study scaling (after, same 32-replication workload)", "",
                "| Workers requested | Threads created | Time | Speedup vs 1 worker |", "|---|---:|---:|---:|"]
        for name in ("study.workers_1", "study.workers_2", "study.workers_4", "study.workers_8", "study.workers_auto"):
            if name not in table:
                continue
            ms = statistics.mean(r["median_ms"] for r in table[name])
            threads = table[name][0]["workload"].split("->")[-1].split(",")[-1].strip().split(" ")[0]
            out.append(f"| {name.split('_')[-1]} | {threads} | {fmt_ms(ms)} | {base / ms:.2f}x |")
        out += [""]
    mem_path = Path(d) / "memory.json"
    if mem_path.exists():
        mem = json.load(open(mem_path, encoding="utf-8"))
        out += ["### Peak memory (resident set, one process per workload; the setup row is the fixed cost of building the 100x100 grid)", "",
                "| Workload | Before | After |", "|---|---:|---:|"]
        for label, row in mem.items():
            out.append(f"| {label} | {row['before']:.1f} MiB | {row['after']:.1f} MiB |")
        out += [""]
    srv_path = Path(d) / "server.json"
    if srv_path.exists():
        srv = json.load(open(srv_path, encoding="utf-8"))["results"]
        out += ["### Real FastAPI server (uvicorn on loopback, Python http.client, after)", "",
                "| Benchmark | Workload | Median | Per request |", "|---|---|---:|---:|"]
        for r in srv:
            out.append(f"| `{r['name']}` | {r['workload']} | {fmt_ms(r['median_ms'])} | {fmt_ms(r['ms_per_request'])} |")
        out += [""]
    floor = Path(d) / "api_floor.json"
    if floor.exists():
        f = json.load(open(floor, encoding="utf-8"))["results"][0]
        out += [f"In-process TestClient request floor (`GET /health`, no engine call): {f['ms_per_op']:.2f} ms per request. "
                "The `http.*` rows above include this fixed cost, which is why routing requests, whose engine time is below "
                "0.1 ms, show no speedup through HTTP even though the direct binding call is faster.", ""]
    # speedups of interest, straight from the tables
    Path(args.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
